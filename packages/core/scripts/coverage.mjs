// Generates COVERAGE.md from data/. Run `npm run coverage` after changing data; a test fails when it is stale.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
/** The entries of every per-state file in a data folder; the file name is the state, so entries do not carry it. */
const readPlaces = (dir) =>
  readdirSync(join(root, dir))
    .filter((f) => f.endsWith(".json"))
    .flatMap((f) => read(`${dir}/${f}`).map((e) => ({ state: f.slice(0, 2), ...e })));

export function buildCoverage() {
  const states = readdirSync(join(root, "data/states"))
    .filter((f) => f.endsWith(".json"))
    .map((f) => ({ code: f.slice(0, 2), ...read(`data/states/${f}`) }))
    .sort((a, b) => a.code.localeCompare(b.code));
  const local = readPlaces("data/cities");
  const cities = (code) => local.filter((c) => c.state === code).map((c) => c.city);
  const reports = (s) =>
    ["llcReport", "corpReport", "lpReport", "llpReport"]
      .filter((k) => s[k])
      .map((k) => k.replace("Report", "").toUpperCase())
      .join(", ") || "none";

  const rows = states.map((s) => {
    const v = s.verification;
    const unconfirmed = v.unconfirmed.length ? v.unconfirmed.join(", ") : "—";
    return `| ${s.code} | ${v.checkedOn} | ${reports(s)} | ${v.dba === "checked" ? "checked" : "unconfirmed"} | ${s.entityTaxDetail ? "structured" : "text"} | ${s.unemployment.year} | ${cities(s.code).join(", ") || "—"} | ${unconfirmed} |`;
  });
  const total = states.length;
  const withUnconfirmed = states.filter((s) => s.verification.unconfirmed.length).length;
  const seeded = new Set(local.map((c) => `${c.state}:${c.city}`)).size;
  const withRules = local.filter((c) => c.items.length > 0).length;
  const none = local.filter((c) => c.status === "none").length;
  const unverified = local.filter((c) => c.status === "unverified").length;
  const counties = readPlaces("data/counties");
  const countyRules = counties.filter((c) => c.items.length > 0).length;
  const topCounties = read("data/top-counties.json").counties;
  const topCountiesCovered = topCounties.filter((t) =>
    counties.some((c) => c.state === t.state && c.county === t.county),
  ).length;
  const top = read("data/top-cities.json").cities;
  const topCovered = top.filter((t) => local.some((c) => c.state === t.state && c.city === t.city)).length;

  return `# Coverage

<!-- Generated by scripts/coverage.mjs from data/; do not edit by hand. -->

What the bundled data covers and how well each part was checked. "Checked" means confirmed against an official
page on the date shown; everything not listed as checked is compiled from public knowledge. See
[CONTRIBUTING.md](CONTRIBUTING.md) to improve a row.

- **Jurisdictions:** ${total} (50 states and DC)
- **States with unconfirmed fields:** ${withUnconfirmed}
- **Seeded cities:** ${seeded}: ${withRules} with city-specific rules, ${none} checked with no general city license or tax, ${unverified} researched but unconfirmed (all other cities get the state's local licensing regime named for the city and county)
- **Seeded counties:** ${counties.length}: ${countyRules} with county-specific filings (mainly business personal property returns), the rest researched but unconfirmed or with nothing county-level
- **300 largest counties** (approximate): ${topCountiesCovered} of ${topCounties.length} covered
- **300 largest cities** (2020 census; ranks beyond 100 are approximate): ${topCovered} of ${top.length} covered

| State | Checked on | Entity reports | DBA level | Gross-receipts / margin tax | UI data year | Seeded cities | Unconfirmed fields |
| ----- | ---------- | -------------- | --------- | --------------------------- | ------------ | ------------- | ------------------ |
${rows.join("\n")}

## Columns

- **Entity reports:** report types with a state-specific rule (LLC, corporation, LP, LLP). Entities without one fall
  back to the corporation report.
- **DBA level:** whether the trade-name filing level and office were checked.
- **Gross-receipts / margin tax:** \`structured\` states expose a threshold and rate and compare it with
  \`annualRevenue\`; others are described in text only.
- **UI data year:** year of the unemployment-insurance wage base and rates (U.S. DOL, Significant Provisions of
  State Unemployment Insurance Laws).
- **Unconfirmed fields:** fields the last review could not confirm; the best estimate is used.
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "COVERAGE.md"), buildCoverage());
  console.log("COVERAGE.md written");
}
